# Logical Operator
# 1. and operator : - If both the operands are True then return True otherwise return False
print(True and True)
print(True and False)

# 2. or operator : - If both the operands are False then return False otherwise return True

print(True or False)
print(False or False)

# 3. not operator : - Oppsite of operands
print(not True)
print(not False)